<?php

namespace App\Services\UserManagement;

use App\Enums\Auth\AccountLifecycle;
use App\Events\Auth\AuthenticationAccountActivated;
use App\Events\Auth\AuthenticationAccountCreated;
use App\Events\Auth\AuthenticationIdentifierChanged;
use App\Models\Profile;
use App\Models\User;
use Illuminate\Support\Facades\DB;
use Illuminate\Support\Facades\Hash;
use Illuminate\Support\Str;
use Illuminate\Validation\ValidationException;

/**
 * Central capability for Authentication Account provisioning and lifecycle.
 *
 * Does not create Persons, assign roles, school participation, or dashboards.
 * Enforces at most one account per Person and respects soft-deleted eligibility.
 */
class UserAccountService
{
    /**
     * Create an Authentication Account for an existing Person.
     *
     * @param  array{
     *     username?: string,
     *     password?: string|null,
     *     auth_phone?: string|null
     * }  $data
     * @param  array{
     *     lifecycle?: string|AccountLifecycle,
     *     force_password_change?: bool,
     *     auto_generate_username?: bool,
     *     send_notification?: bool
     * }  $options
     */
    /**
     * Create an Authentication Account for a Person (Profile) with one-to-one cardinality.
     *
     * @param  Profile  $person  Person that must not already have an account or be soft-deleted.
     * @param  array  $data  Optional username, password, auth_phone.
     * @param  array  $options  lifecycle, force_password_change, auto_generate_username, send_notification.
     * @return User  Newly created account linked via profiles.user_id.
     *
     * Side effects: locks person row, inserts users row, sets profiles.user_id, may notify.
     * Does not assign roles. Does not auto-generate passwords when none is supplied
     * (password remains null; passwordAutoGenerated event flag is false).
     *
     * @throws \Illuminate\Validation\ValidationException
     */
    public function createForPerson(
        Profile $person,
        array $data = [],
        array $options = []
    ): User {
        $options = array_merge([
            'lifecycle' => null,
            'force_password_change' => false,
            'auto_generate_username' => true,
            'send_notification' => true,
        ], $options);

        if ($person->trashed()) {
            throw ValidationException::withMessages([
                'person' => 'Cannot create an authentication account for a deleted person.',
            ]);
        }

        $plainPassword = array_key_exists('password', $data) ? $data['password'] : null;
        $lifecycle = $this->resolveLifecycleForCreate($options['lifecycle'] ?? null, $plainPassword);

        if ($lifecycle === AccountLifecycle::Active) {
            if ($plainPassword === null || $plainPassword === '') {
                throw ValidationException::withMessages([
                    'password' => 'Active accounts require usable credentials.',
                ]);
            }
            if (strlen((string) $plainPassword) < 8) {
                throw ValidationException::withMessages([
                    'password' => 'Password must be at least 8 characters.',
                ]);
            }
        } elseif ($plainPassword !== null && $plainPassword !== '' && strlen((string) $plainPassword) < 8) {
            throw ValidationException::withMessages([
                'password' => 'Password must be at least 8 characters.',
            ]);
        }

        $username = $this->resolveUsername($person, $data, (bool) $options['auto_generate_username']);

        if (User::where('username', $username)->exists()) {
            throw ValidationException::withMessages([
                'username' => 'This username is already taken.',
            ]);
        }

        $authPhone = isset($data['auth_phone']) ? $this->normalizePhone($data['auth_phone']) : null;

        return DB::transaction(function () use (
            $person,
            $username,
            $plainPassword,
            $lifecycle,
            $options,
            $authPhone
        ) {
            // Lock the person row to prevent concurrent dual attachment.
            /** @var Profile $locked */
            $locked = Profile::query()->whereKey($person->id)->lockForUpdate()->firstOrFail();

            if ($locked->trashed()) {
                throw ValidationException::withMessages([
                    'person' => 'Cannot create an authentication account for a deleted person.',
                ]);
            }

            if ($locked->user_id !== null) {
                throw ValidationException::withMessages([
                    'person' => 'This person already has an authentication account.',
                ]);
            }

            $user = User::create([
                'username' => $username,
                'password' => $plainPassword !== null && $plainPassword !== ''
                    ? $plainPassword
                    : null,
                'lifecycle' => $lifecycle->value,
                'force_password_change' => (bool) $options['force_password_change'],
                'auth_email_verified_at' => null,
                'auth_email_enabled' => false,
                'auth_phone' => $authPhone,
                'auth_phone_verified_at' => null,
                'auth_phone_enabled' => false,
            ]);

            $locked->update(['user_id' => $user->id]);

            // Domain event must not carry credentials.
            // passwordAutoGenerated is true only when this service actually generated
            // a password value. Absence of a supplied password does not mean one was
            // auto-generated — accounts may be provisioned without a password.
            $passwordWasAutoGenerated = false;
            event(new AuthenticationAccountCreated(
                account: $user,
                passwordAutoGenerated: $passwordWasAutoGenerated,
            ));

            // Narrow credential delivery (not via domain event).
            if ($options['send_notification'] && is_string($plainPassword) && $plainPassword !== '' && filled($person->email)) {
                try {
                    $email = $person->email;
                    if (filled($email)) {
                        \Illuminate\Support\Facades\Notification::route('mail', $email)
                            ->notify(new \App\Notifications\AccountCreatedNotification($user, $plainPassword));
                    }
                } catch (\Throwable $e) {
                    \Illuminate\Support\Facades\Log::warning('Account credential notification failed: '.$e->getMessage());
                }
            }

            return $user->load('profile');
        });
    }

    /**
     * Activate a Provisioned account with usable credentials.
     */
    public function activate(User $account, string $password): User
    {
        if (strlen($password) < 8) {
            throw ValidationException::withMessages([
                'password' => 'Password must be at least 8 characters.',
            ]);
        }

        return DB::transaction(function () use ($account, $password) {
            /** @var User $locked */
            $locked = User::query()->whereKey($account->id)->lockForUpdate()->firstOrFail();

            if ($locked->lifecycle === AccountLifecycle::Active) {
                // Idempotent: already active — do not re-dispatch activation event.
                return $locked;
            }

            if ($locked->lifecycle !== AccountLifecycle::Provisioned) {
                throw ValidationException::withMessages([
                    'lifecycle' => 'Only provisioned accounts can be activated.',
                ]);
            }

            $locked->forceFill([
                'password' => $password,
                'lifecycle' => AccountLifecycle::Active->value,
            ])->save();

            event(new AuthenticationAccountActivated($locked));

            return $locked->refresh();
        });
    }


    public function setForcePasswordChange(User $account, bool $required): User
    {
        $account->forceFill([
            'force_password_change' => $required,
        ])->save();

        return $account->refresh();
    }

    public function setAuthEmailEnabled(User $account, bool $enabled): User
    {
        if ($enabled) {
            if ($account->profile === null || ! filled($account->profile->email)) {
                throw ValidationException::withMessages([
                    'auth_email' => 'Person must have a primary email before email login can be enabled.',
                ]);
            }
            if ($account->auth_email_verified_at === null) {
                throw ValidationException::withMessages([
                    'auth_email' => 'Email must be verified before it can be enabled for login.',
                ]);
            }
        }

        $account->forceFill([
            'auth_email_enabled' => $enabled,
        ])->save();

        event(new AuthenticationIdentifierChanged($account, 'auth_email'));

        return $account->refresh();
    }

    public function setAuthPhone(User $account, ?string $phone): User
    {
        $normalized = $this->normalizePhone($phone);

        $account->forceFill([
            'auth_phone' => $normalized,
            'auth_phone_verified_at' => null,
            'auth_phone_enabled' => false,
        ])->save();

        event(new AuthenticationIdentifierChanged($account, 'auth_phone'));

        return $account->refresh();
    }

    /**
     * Mark the linked Person primary email as verified for authentication.
     * Does not enable login by itself.
     */

    public function markAuthPhoneVerified(User $account): User
    {
        // Phase 1: possession-proof challenge is not implemented.
        // Do not mark phones verified without a genuine verification workflow.
        throw ValidationException::withMessages([
            'auth_phone' => 'Phone verification is not available until a possession-proof challenge is implemented.',
        ]);
    }

    public function setAuthPhoneEnabled(User $account, bool $enabled): User
    {
        if ($enabled) {
            if (! filled($account->auth_phone) || $account->auth_phone_verified_at === null) {
                throw ValidationException::withMessages([
                    'auth_phone' => 'Authentication phone must be verified before it can be enabled for login.',
                ]);
            }

            // Unique enabled auth phone: fail closed if another account already has this phone enabled.
            $conflict = User::query()
                ->where('auth_phone', $account->auth_phone)
                ->where('auth_phone_enabled', true)
                ->where('id', '!=', $account->id)
                ->exists();
            if ($conflict) {
                throw ValidationException::withMessages([
                    'auth_phone' => 'This authentication phone is already enabled on another account.',
                ]);
            }
        }

        $account->forceFill([
            'auth_phone_enabled' => $enabled,
        ])->save();

        event(new AuthenticationIdentifierChanged($account, 'auth_phone'));

        return $account->refresh();
    }

    /**
     * Admin/service password reset: sets a new credential and requires change on next login.
     * Does not dispatch AuthenticationAccountCreated.
     */
    public function resetPassword(User $account, ?string $newPassword = null, bool $notify = false): string
    {
        $plain = $newPassword ?: \Illuminate\Support\Str::random(12);
        if (strlen($plain) < 8) {
            throw ValidationException::withMessages([
                'password' => 'Password must be at least 8 characters.',
            ]);
        }

        // Admin credential reset: never bypass activation semantics.
        // Provisioned accounts remain Provisioned; Active accounts stay Active.
        // Always require password change on next login.
        $account->forceFill([
            'password' => $plain,
            'force_password_change' => true,
        ])->save();

        if ($notify) {
            // Controlled credential delivery (narrow path) — do not use general domain event for plaintext.
            try {
                \Illuminate\Support\Facades\Notification::route('mail', $account->profile?->email)
                    ->notify(new \App\Notifications\AdminResetPasswordNotification($plain, $account));
            } catch (\Throwable $e) {
                \Illuminate\Support\Facades\Log::warning('Admin reset notification failed: '.$e->getMessage());
            }
        }

        return $plain;
    }


    public function markAuthEmailVerified(User $account): User
    {
        if ($account->profile === null || ! filled($account->profile->email)) {
            throw ValidationException::withMessages([
                'auth_email' => 'Person must have a primary email to verify.',
            ]);
        }

        $account->forceFill([
            'auth_email_verified_at' => now(),
        ])->save();

        return $account->refresh();
    }

    private function resolveLifecycleForCreate(
        AccountLifecycle|string|null $requested,
        ?string $plainPassword
    ): AccountLifecycle {
        if ($requested === null) {
            return ($plainPassword !== null && $plainPassword !== '')
                ? AccountLifecycle::Active
                : AccountLifecycle::Provisioned;
        }

        $lifecycle = $requested instanceof AccountLifecycle
            ? $requested
            : AccountLifecycle::from((string) $requested);

        if ($lifecycle === AccountLifecycle::Active && ($plainPassword === null || $plainPassword === '')) {
            throw ValidationException::withMessages([
                'password' => 'Active accounts require usable credentials.',
            ]);
        }

        return $lifecycle;
    }

    private function resolveUsername(Profile $person, array $data, bool $allowAutoGenerate): string
    {
        if (! empty($data['username'])) {
            return strtolower(trim((string) $data['username']));
        }

        if ($allowAutoGenerate) {
            $prefix = strtolower(substr($person->first_name ?? 'user', 0, 1).($person->last_name ?? 'user'));
            $prefix = preg_replace('/[^a-z0-9]/i', '', $prefix) ?: 'user';

            return $prefix.'_'.Str::lower(Str::random(4));
        }

        $email = $person->email;
        if ($email) {
            $prefix = Str::before(strtolower($email), '@');
            $prefix = preg_replace('/[^a-z0-9]/i', '', $prefix) ?: 'user';

            return $prefix.'_'.Str::lower(Str::random(3));
        }

        throw ValidationException::withMessages([
            'username' => 'Unable to determine username. Please provide one manually.',
        ]);
    }

    private function normalizePhone(?string $phone): ?string
    {
        if ($phone === null || trim($phone) === '') {
            return null;
        }

        // Preserve project convention: store digits and leading + only.
        $normalized = preg_replace('/[^\d+]/', '', $phone);

        return $normalized !== '' ? $normalized : null;
    }
}
